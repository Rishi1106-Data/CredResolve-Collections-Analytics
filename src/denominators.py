"""
Denominator audit: what is a defensible denominator for a 'recovery rate'?   Run from repo root AFTER metrics.py:
    python src/denominators.py        -> reports/denominator_audit.md, reports/denominator_by_status.csv (+ updates headline_numbers.json)

The question: can 'recovery / static outstanding balance' be called a collection rate? Only if the outstanding balance
is the balance that was ELIGIBLE for collection in the period. We test whether the data lets us build that balance.
"""
import json
import pandas as pd

RAW = "collections_30k_dataset"
acc = pd.read_csv("golden/accounts_clean.csv")
pay = pd.read_csv("golden/payments_clean.csv", parse_dates=["event_at"])
hist = pd.read_csv(f"{RAW}/account_status_history.csv", parse_dates=["event_at", "recorded_at"])
ok = pay[pay.is_success & (pay.event_at < "2026-08-01")]                 # Jan-Jul complete months
HEAD = json.load(open("reports/headline_numbers.json"))
L = ["# Denominator audit (generated by src/denominators.py)\n",
     "**Purpose:** decide what 'recovery rate' can honestly mean. Metrics below use SUCCESS payments, 1 Jan – 31 Jul 2026 (212 days).\n"]

# ---- 1. the candidate denominators -------------------------------------------------------------------------
tot_out = acc.outstanding_amount.sum()
rec = ok.amount.sum()
L += ["## 1. Candidate denominators and what each one means\n",
      "| Metric | Numerator | Denominator | Value | Status |", "|---|---|---|---:|---|",
      f"| Successful payment amount | Σ SUCCESS payments | – | ₹{rec/1e7:.1f} Cr | **Measured fact** |",
      f"| Recovery per calendar day | Σ SUCCESS payments | {len(pd.date_range('2026-01-01','2026-07-31'))} calendar days | ₹{rec/1e7/212:.3f} Cr/day | **Measured fact**; removes month-length effect |",
      f"| Recovery per base account | Σ SUCCESS payments | all {len(acc):,} accounts in the snapshot | ₹{rec/len(acc):,.0f} per account | Index: includes PAID/CLOSED/WRITEOFF accounts |",
      f"| Paying-account share | accounts with ≥1 SUCCESS payment | all {len(acc):,} accounts | {ok.account_id.nunique()/len(acc)*100:.1f}% over Jan–Jul | Index: same population caveat |",
      f"| Recovery ÷ static outstanding | Σ SUCCESS payments | Σ `outstanding_amount` snapshot = ₹{tot_out/1e7:,.0f} Cr | {rec/tot_out*100:.1f}% over Jan–Jul | **NOT a validated collection rate** – index only |", ""]
HEAD.update(den_recovery_pct_static=round(rec / tot_out * 100, 1), den_static_outstanding_cr=round(tot_out / 1e7))

# ---- 2. does the account status separate collectible from non-collectible accounts? --------------------------
a = ok.merge(acc[["account_id", "status"]], on="account_id")
g = a.groupby("status").agg(success_payments=("amount", "size"), recovery_cr=("amount", lambda s: s.sum() / 1e7), paying_accounts=("account_id", "nunique"))
g["accounts"] = acc.status.value_counts(); g["outstanding_cr"] = acc.groupby("status").outstanding_amount.sum() / 1e7
g["paying_share_pct"] = g.paying_accounts / g.accounts * 100
g["recovery_pct_of_outstanding"] = g.recovery_cr / g.outstanding_cr * 100
g = g.round(2); g.to_csv("reports/denominator_by_status.csv")
L += ["## 2. Do PAID / CLOSED / WRITEOFF accounts behave differently from ACTIVE ones?\n",
      "If status identified ineligible accounts, they would have (almost) no recovery. They do not:\n",
      g[["accounts", "outstanding_cr", "paying_accounts", "paying_share_pct", "recovery_cr", "recovery_pct_of_outstanding"]].to_markdown(),
      "",
      f"- {1 - (acc.status == 'ACTIVE').mean():.0%} of accounts are PAID, CLOSED or WRITEOFF, yet they account for "
      f"{a[a.status != 'ACTIVE'].amount.sum()/a.amount.sum()*100:.0f}% of SUCCESS rupees, with the same paying share and recovery-to-balance ratio as ACTIVE accounts.",
      "- So `accounts.status` is either a snapshot taken at a different time from the payments, or is not usable to define eligibility. "
      "Excluding non-ACTIVE accounts from the denominator would therefore also require dropping their payments – the rate would be unchanged (≈12%) but the base would shrink 75%.",
      ""]
HEAD.update(den_nonactive_share_accts_pct=round((1 - (acc.status == "ACTIVE").mean()) * 100), den_nonactive_share_rs_pct=round(a[a.status != "ACTIVE"].amount.sum() / a.amount.sum() * 100),
            den_rec_pct_status_lo=float(g.recovery_pct_of_outstanding.min()), den_rec_pct_status_hi=float(g.recovery_pct_of_outstanding.max()))

# ---- 3. other eligibility signals ------------------------------------------------------------------------------
cum = ok.groupby("account_id").amount.sum().rename("recovered").to_frame().join(acc.set_index("account_id")[["outstanding_amount", "dpd", "principal_amount"]])
over = int((cum.recovered > cum.outstanding_amount).sum())
dpd0 = acc[acc.dpd == 0]
L += ["## 3. Other checks on the outstanding balance\n",
      f"- Accounts that recovered MORE than their snapshot outstanding balance during Jan–Jul: **{over:,}** ({over/len(cum)*100:.1f}% of paying accounts) – impossible if the balance were the amount due at the start of the period.",
      f"- Outstanding balance above original principal: {(acc.outstanding_amount > acc.principal_amount).mean()*100:.0f}% of accounts (possible with interest/fees, but unverified).",
      f"- Accounts with DPD = 0 (not overdue): {len(dpd0):,} ({len(dpd0)/len(acc)*100:.1f}%); {ok[ok.account_id.isin(dpd0.account_id)].account_id.nunique():,} of them paid. Balance is not overdue-only.",
      "- `outstanding_amount`, `dpd`, `status` are single snapshot columns: there is no balance-at-start-of-month, no write-off date and no 'eligible for collection' flag.", ""]
HEAD.update(den_accts_over_outstanding=over, den_accts_over_outstanding_pct=round(over / len(cum) * 100, 1), den_dpd0_accounts=len(dpd0))

# ---- 4. status history: can eligibility be rebuilt over time? ----------------------------------------------------
hs = hist.sort_values("event_at")
last = hs.groupby("account_id").last().status
m = acc.set_index("account_id").status.to_frame().join(last.rename("hist_last"))
agree = (m.status == m.hist_last)[m.hist_last.notna()].mean()
TERM = ["PAID", "CLOSED", "WRITEOFF"]
rows = []
for ms in pd.date_range("2026-02-01", "2026-08-01", freq="MS"):
    asof = hs[hs.event_at < ms].groupby("account_id").last().status
    rows.append({"as_of": ms.date().isoformat(), "accounts_with_known_status": len(asof), "terminal_PAID_CLOSED_WRITEOFF": int(asof.isin(TERM).sum()),
                 "terminal_share_pct": round(asof.isin(TERM).mean() * 100, 1)})
tm = pd.DataFrame(rows)
pp = pd.merge_asof(ok.sort_values("event_at"), hs[["account_id", "event_at", "status"]].rename(columns={"event_at": "st_at", "status": "st"}).sort_values("st_at"),
                   left_on="event_at", right_on="st_at", by="account_id")
known = pp[pp.st.notna()]
term_rs = known[known.st.isin(TERM)].amount.sum() / known.amount.sum() * 100
L += ["## 4. `account_status_history` – can eligibility be rebuilt over time?\n",
      f"- {len(hist):,} status events for {hist.account_id.nunique():,} accounts ({len(acc)-hist.account_id.nunique():,} accounts have no history). Statuses: {', '.join(sorted(hist.status.unique()))}.",
      f"- Latest historical status equals `accounts.status` for only {agree*100:.1f}% of accounts (≈ chance), so the two sources contradict each other. "
      f"`recorded_at` is earlier than `event_at` in {(hist.recorded_at < hist.event_at).mean()*100:.0f}% of rows.",
      f"- Share of SUCCESS rupees received while the account's latest known status was PAID, CLOSED or WRITEOFF: **{term_rs:.1f}%** – status does not stop payments.",
      "- Share of accounts in a terminal status, as of each month start (a shrinking share would suggest unsuccessful accounts being removed from the base):\n",
      tm.to_markdown(index=False), "",
      "- The terminal share is flat at ≈43%: no sign of accounts progressively leaving the population (denominator manipulation is not detectable). "
      "This is a statement about this data, not proof about the source system's reporting.", ""]
HEAD.update(den_hist_agree_pct=round(agree * 100, 1), den_terminal_rs_pct=round(term_rs, 1), den_terminal_share_lo=float(tm.terminal_share_pct.min()), den_terminal_share_hi=float(tm.terminal_share_pct.max()))

L += ["## 5. Conclusion and wording rules\n",
      "1. An **eligible outstanding balance cannot be established** from this extract. No table gives the balance due at the start of a period, an eligibility flag, or a reliable status date.",
      "2. Therefore `Recovery ÷ static outstanding` is reported as **'recovery as % of static outstanding snapshot (index)'**, never as 'collection rate' or 'recovery rate'. Its value (≈12% over Jan–Jul; ≈1.6–1.8% per month) is only useful for comparing months, because the denominator is constant.",
      "3. The headline performance measures are the ones with defensible denominators: **₹ recovered per calendar day**, **number and share of accounts paying**, and **average payment size**.",
      "4. To compute a true recovery rate the company needs: start-of-period outstanding per account, an eligibility rule (e.g. DPD>0 and not written-off at that date), dated status changes, and write-off dates. Until then, any 'recovery rate' quoted from this data should carry this caveat.",
      "5. The earlier statement 'no accounts disappear from the denominator' remains literally true for the fixed 30,000-account base, but it does not validate the denominator."]
open("reports/denominator_audit.md", "w", encoding="utf-8").write("\n".join(L) + "\n")
json.dump(HEAD, open("reports/headline_numbers.json", "w", encoding="utf-8"), indent=1)
print("\n".join(L))
